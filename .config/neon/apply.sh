#!/usr/bin/env bash
# Applies the neon color to the whole theme (waybar, wofi, GTK, Hyprland,
# hyprlock, the SDDM login screen, the kitty terminal and Neovim)
# Usage: apply.sh [RRGGBB] [--no-reload]
#   without a color: reapplies the saved color (or the default white)

set -euo pipefail

readonly CONFIG_DIR="$HOME/.config"
readonly STATE="$CONFIG_DIR/neon/color"
readonly DEFAULT="ffffff"

reload=true
hex=""
for arg in "$@"; do
    case "$arg" in
        --no-reload) reload=false ;;
        *)           hex="$arg" ;;
    esac
done

if [[ -z "$hex" && -f "$STATE" ]]; then
    hex=$(<"$STATE")
fi
hex="${hex:-$DEFAULT}"
hex="${hex#\#}"
hex="${hex,,}"

if [[ ! "$hex" =~ ^[0-9a-f]{6}$ ]]; then
    echo "Invalid color: '$hex' (use the RRGGBB format)" >&2
    exit 1
fi

printf '%s\n' "$hex" > "$STATE"

# ─── Generated files ────────────────────────────────────────
# Each one has a default (white) version in the repository

cat > "$CONFIG_DIR/colors/neon.css" <<CSS
/* Generated by ~/.config/neon/apply.sh */
@define-color neon #$hex;
CSS

cat > "$CONFIG_DIR/hypr/neon.lua" <<LUA
-- Generated by ~/.config/neon/apply.sh
neon = "$hex"
LUA

cat > "$CONFIG_DIR/hypr/neon.conf" <<CONF
# Generated by ~/.config/neon/apply.sh
\$neon       = rgb($hex)
\$neon_dim   = rgba(${hex}80)
\$neon_faint = rgba(${hex}40)
\$neon_glow  = rgba(${hex}aa)
CONF

# Login screen: the installer makes this file writable by the user
readonly SDDM_USER_CONF="/usr/share/sddm/themes/cyberpunk/theme.conf.user"
if [[ -w "$SDDM_USER_CONF" ]]; then
    printf '[General]\ncolor=#%s\n' "$hex" > "$SDDM_USER_CONF"
fi

# Terminal: the neon at full, 75% and 40% brightness
shade() {
    local percent=$1
    printf '%02x%02x%02x' \
        $(( 0x${hex:0:2} * percent / 100 )) \
        $(( 0x${hex:2:2} * percent / 100 )) \
        $(( 0x${hex:4:2} * percent / 100 ))
}
dim=$(shade 75)
faint=$(shade 40)

# The 16 terminal colors (0–7 regular, 8–15 bright). Text and cursor follow
# the neon; the other colors are neon versions of the usual ones, so
# errors, diffs and file types stay readable
palette=(
    000000 ff2a6d 05ffa1 ffd300 3d8bff b026ff 00e5ff "$dim"
    "$faint" ff2a6d 05ffa1 ffd300 3d8bff b026ff 00e5ff "$hex"
)

if [[ -d "$CONFIG_DIR/kitty" ]]; then
    {
        printf '# Generated by ~/.config/neon/apply.sh\n'
        printf 'foreground #%s\nbackground #000000\n\n' "$hex"
        printf 'cursor            #%s\ncursor_text_color #000000\n\n' "$hex"
        printf 'selection_foreground #000000\nselection_background #%s\n' "$hex"
        printf 'url_color            #%s\n\n' "$hex"
        printf '# Text and cursor follow the neon; the other colors are neon versions\n'
        printf '# of the usual ones, so errors, diffs and file types stay readable\n'
        for i in {0..15}; do
            printf 'color%-2d #%s\n' "$i" "${palette[i]}"
            if (( i == 7 )); then printf '\n'; fi
        done
        printf '\n# Split borders and tabs\n'
        printf 'active_border_color   #%s\ninactive_border_color #%s\n' "$hex" "$faint"
        printf 'bell_border_color     #ff2a6d\n'
        printf 'tab_bar_background      #000000\n'
        printf 'active_tab_foreground   #000000\nactive_tab_background   #%s\n' "$hex"
        printf 'inactive_tab_foreground #%s\ninactive_tab_background #000000\n' "$dim"
    } > "$CONFIG_DIR/kitty/neon.conf"
fi

# ─── Reload ─────────────────────────────────────────────────
# wofi and hyprlock read the color when they open; GTK apps that are
# already open (Thunar) only change after a restart
if $reload; then
    if [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
        hyprctl reload >/dev/null
    fi
    pkill -SIGUSR2 -x waybar || true

    # Open kitty windows reload their config (and so neon.conf)
    pkill -USR1 -u "$(id -u)" -x kitty || true

    # Open Neovim instances that use the theme switch to the new color
    if command -v nvim >/dev/null; then
        for server in "${XDG_RUNTIME_DIR:-/tmp}"/nvim.*.0; do
            [[ -S "$server" ]] || continue
            nvim --server "$server" --remote-expr \
                'execute(get(g:, "colors_name", "") ==# "cyberpunk" ? "colorscheme cyberpunk" : "")' \
                >/dev/null 2>&1 || true
        done
    fi
fi