#!/usr/bin/env bash
# Applies the neon color to the whole theme (waybar, wofi, GTK, Hyprland and hyprlock)
# Usage: apply.sh [RRGGBB] [--no-reload]
#   without a color: reapplies the saved color (or the default white)

set -euo pipefail

readonly CONFIG_DIR="$HOME/.config"
readonly STATE="$CONFIG_DIR/neon/color"
readonly DEFAULT="ffffff"

reload=true
hex=""
for arg in "$@"; do
    case "$arg" in
        --no-reload) reload=false ;;
        *)           hex="$arg" ;;
    esac
done

if [[ -z "$hex" && -f "$STATE" ]]; then
    hex=$(<"$STATE")
fi
hex="${hex:-$DEFAULT}"
hex="${hex#\#}"
hex="${hex,,}"

if [[ ! "$hex" =~ ^[0-9a-f]{6}$ ]]; then
    echo "Invalid color: '$hex' (use the RRGGBB format)" >&2
    exit 1
fi

printf '%s\n' "$hex" > "$STATE"

# ─── Generated files ────────────────────────────────────────
# Each one has a default (white) version in the repository

cat > "$CONFIG_DIR/colors/neon.css" <<CSS
/* Generated by ~/.config/neon/apply.sh */
@define-color neon #$hex;
CSS

cat > "$CONFIG_DIR/hypr/neon.lua" <<LUA
-- Generated by ~/.config/neon/apply.sh
neon = "$hex"
LUA

cat > "$CONFIG_DIR/hypr/neon.conf" <<CONF
# Generated by ~/.config/neon/apply.sh
\$neon       = rgb($hex)
\$neon_dim   = rgba(${hex}80)
\$neon_faint = rgba(${hex}40)
\$neon_glow  = rgba(${hex}aa)
CONF

# ─── Reload ─────────────────────────────────────────────────
# wofi and hyprlock read the color when they open; GTK apps that are
# already open (Thunar) only change after a restart
if $reload; then
    if [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
        hyprctl reload >/dev/null
    fi
    pkill -SIGUSR2 -x waybar || true
fi
